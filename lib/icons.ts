// Mirrors Arduino_code/include/icons.h row-for-row. Keep both in sync — the
// editor must never let someone pick (or preview) an icon the firmware can't
// actually draw the same way.
export const ICON_BITMAPS: Record<string, number[]> = {
  dot: [0x0000, 0x07e0, 0x1ff8, 0x3ffc, 0x7ffe, 0x7ffe, 0xffff, 0xffff, 0xffff, 0xffff, 0x7ffe, 0x7ffe, 0x3ffc, 0x1ff8, 0x07e0, 0x0000],
  ring: [0x0000, 0x0420, 0x1818, 0x300c, 0x6006, 0x6006, 0xc003, 0xc003, 0xc003, 0xc003, 0x6006, 0x6006, 0x300c, 0x1818, 0x0420, 0x0000],
  cross: [0xc003, 0xe007, 0x700e, 0x381c, 0x1c38, 0x0e70, 0x07e0, 0x03c0, 0x03c0, 0x07e0, 0x0e70, 0x1c38, 0x381c, 0x700e, 0xe007, 0xc003],
  triangle: [0x0180, 0x0180, 0x03c0, 0x03c0, 0x07e0, 0x07e0, 0x0ff0, 0x0ff0, 0x1ff8, 0x1ff8, 0x3ffc, 0x3ffc, 0x7ffe, 0x7ffe, 0xffff, 0xffff],
  square: [0xffff, 0xffff, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xc003, 0xffff, 0xffff],
}

// Icons are a fixed 16x16 bitmap grid; an icon's drawn size is this × scale.
export const ICON_GRID_SIZE = 16

export function drawIcon(
  ctx: CanvasRenderingContext2D,
  iconId: string,
  x: number,
  y: number,
  color: string,
  scale: number,
) {
  const rows = ICON_BITMAPS[iconId]
  if (!rows) return
  ctx.fillStyle = color
  for (let row = 0; row < ICON_GRID_SIZE; row++) {
    for (let col = 0; col < ICON_GRID_SIZE; col++) {
      if (rows[row] & (1 << (ICON_GRID_SIZE - 1 - col))) {
        ctx.fillRect(x + col * scale, y + row * scale, scale, scale)
      }
    }
  }
}
